"""Human-facing API docs, served from the committed specs.

    /                landing page linking both surfaces
    /swagger         Swagger UI rendering docs/swagger/swagger.json (REST, Try it out)
    /swagger/doc.json, /swagger/doc.yaml   the committed OpenAPI spec, verbatim
    /swagger/index.css, /swagger/swagger-initializer.js   the BCBP theme and UI bootstrap
    /asyncapi.yaml   the committed spec (``api/asyncapi.yaml``, generated by
                     ``scripts/gen_api_docs.py``), served verbatim
    /asyncapi        the themed event catalogue (``api/asyncapi.html``, as in the IAM services)

Plain Starlette routes, not ``APIRoute``s: they are neither part of the OpenAPI document nor
subject to the identity-declaration rule, like ``/docs`` itself.
"""

from __future__ import annotations

from pathlib import Path

from fastapi import FastAPI
from starlette.requests import Request
from starlette.responses import HTMLResponse, PlainTextResponse, Response

ROOT = Path(__file__).resolve().parents[3]
ASYNCAPI_SPEC = ROOT / "api" / "asyncapi.yaml"
ASYNCAPI_HTML = ROOT / "api" / "asyncapi.html"
SWAGGER_DIR = ROOT / "docs" / "swagger"

_SWAGGER_PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>REST API — Swagger UI</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="stylesheet" href="https://unpkg.com/swagger-ui-dist@5.17.14/swagger-ui.css">
<link rel="stylesheet" href="/swagger/index.css">
</head><body><div id="swagger-ui"></div>
<script src="https://unpkg.com/swagger-ui-dist@5.17.14/swagger-ui-bundle.js"></script>
<script src="https://unpkg.com/swagger-ui-dist@5.17.14/swagger-ui-standalone-preset.js"></script>
<script src="/swagger/swagger-initializer.js"></script>
</body></html>
"""

# Same options as the IAM services' initializer: standalone layout, definition-order tags and
# operations (identity sorters), and the toggle plugin that keeps nested model rows collapsible.
_SWAGGER_INIT = """window.onload = function () {
  const KeepModelTogglePlugin = function () {
    return {
      wrapComponents: {
        ModelCollapse: function (Original, system) {
          return function (props) {
            var next = Object.assign({}, props);
            if (props.collapsedContent === "[...]") { next.hideSelfOnExpand = false; }
            return system.React.createElement(Original, next);
          };
        }
      }
    };
  };
  window.ui = SwaggerUIBundle({
    url: "/swagger/doc.json",
    dom_id: "#swagger-ui",
    validatorUrl: null,
    persistAuthorization: false,
    presets: [SwaggerUIBundle.presets.apis, SwaggerUIStandalonePreset],
    plugins: [SwaggerUIBundle.plugins.DownloadUrl, KeepModelTogglePlugin],
    layout: "StandaloneLayout",
    docExpansion: "list",
    deepLinking: true,
    defaultModelsExpandDepth: 1,
    tagsSorter: function () { return 0; },
    operationsSorter: function () { return 0; }
  });
};
"""

_LANDING = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>LLM Retrieval &amp; Generation — API docs</title>
<meta name="viewport" content="width=device-width, initial-scale=1"></head>
<body style="font-family:system-ui;max-width:40rem;margin:3rem auto;padding:0 1rem">
<h1>LLM Retrieval &amp; Generation</h1>
<ul>
<li><a href="/swagger">/swagger</a> — REST API (Swagger UI)</li>
<li><a href="/asyncapi">/asyncapi</a> — events (AsyncAPI)</li>
<li><a href="/swagger/doc.json">/swagger/doc.json</a> · <a href="/swagger/doc.yaml">doc.yaml</a>
 · <a href="/asyncapi.yaml">/asyncapi.yaml</a> — raw specs</li>
</ul></body></html>
"""


async def asyncapi_yaml(request: Request) -> Response:
    """The raw spec; 404 when the file is not shipped next to the package."""
    if not ASYNCAPI_SPEC.is_file():
        return PlainTextResponse("asyncapi.yaml is not available", status_code=404)
    return Response(ASYNCAPI_SPEC.read_bytes(), media_type="application/yaml")


def _file(path: Path, media_type: str) -> Response:
    if not path.is_file():
        return PlainTextResponse(f"{path.name} is not available", status_code=404)
    return Response(path.read_bytes(), media_type=media_type)


async def swagger_json(request: Request) -> Response:
    """The committed OpenAPI spec (JSON)."""
    return _file(SWAGGER_DIR / "swagger.json", "application/json")


async def swagger_yaml(request: Request) -> Response:
    """The committed OpenAPI spec (YAML)."""
    return _file(SWAGGER_DIR / "swagger.yaml", "application/yaml")


async def swagger_theme(request: Request) -> Response:
    """The BCBP dark theme (``docs/swagger/swagger-theme.css``), copied from the IAM services."""
    return _file(SWAGGER_DIR / "swagger-theme.css", "text/css")


async def swagger_initializer(request: Request) -> Response:
    """Swagger UI bootstrap script."""
    return Response(_SWAGGER_INIT, media_type="application/javascript")


async def swagger_page(request: Request) -> Response:
    """Swagger UI over ``/swagger/doc.json``."""
    return HTMLResponse(_SWAGGER_PAGE)


async def landing(request: Request) -> Response:
    """Links to both doc surfaces."""
    return HTMLResponse(_LANDING)


async def asyncapi_page(request: Request) -> Response:
    """The BCBP-themed event catalogue (``api/asyncapi.html``, rendered by the generator)."""
    if not ASYNCAPI_HTML.is_file():
        return PlainTextResponse("asyncapi.html is not available", status_code=404)
    env = request.app.state.settings.environment.upper() or "DEV"
    return HTMLResponse(ASYNCAPI_HTML.read_text(encoding="utf-8").replace("{{ENV}}", env))


def register_api_docs(app: FastAPI) -> None:
    """Mount the AsyncAPI routes on ``app``."""
    app.add_route("/", landing, include_in_schema=False)
    app.add_route("/swagger", swagger_page, include_in_schema=False)
    app.add_route("/swagger/index.css", swagger_theme, include_in_schema=False)
    app.add_route("/swagger/swagger-initializer.js", swagger_initializer, include_in_schema=False)
    app.add_route("/swagger/doc.json", swagger_json, include_in_schema=False)
    app.add_route("/swagger/doc.yaml", swagger_yaml, include_in_schema=False)
    app.add_route("/asyncapi.yaml", asyncapi_yaml, include_in_schema=False)
    app.add_route("/asyncapi", asyncapi_page, include_in_schema=False)
